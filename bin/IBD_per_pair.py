def parse_finite_float(
    value: str,
    column_name: str,
    input_path: Path,
    line_number: int,
    minimum: float | None = None,
) -> float:
    """Parse and validate a floating-point value."""

    try:
        parsed_value = float(value)
    except (TypeError, ValueError) as error:
        raise SystemExit(
            "ERROR: invalid numeric value in summary file.\n"
            f"File: {input_path}\n"
            f"Line: {line_number}\n"
            f"Column: {column_name}\n"
            f"Observed value: {value!r}"
        ) from error

    if not math.isfinite(parsed_value):
        raise SystemExit(
            "ERROR: a non-finite numeric value was found.\n"
            f"File: {input_path}\n"
            f"Line: {line_number}\n"
            f"Column: {column_name}\n"
            f"Observed value: {value!r}"
        )

    if minimum is not None and parsed_value < minimum:
        raise SystemExit(
            "ERROR: numeric value is below the permitted minimum.\n"
            f"File: {input_path}\n"
            f"Line: {line_number}\n"
            f"Column: {column_name}\n"
            f"Minimum: {minimum}\n"
            f"Observed value: {parsed_value}"
        )

    return parsed_value


def parse_nonnegative_integer(
    value: str,
    column_name: str,
    input_path: Path,
    line_number: int,
) -> int:
    """Parse and validate a non-negative integer."""

    try:
        parsed_value = int(value)
    except (TypeError, ValueError) as error:
        raise SystemExit(
            "ERROR: invalid integer value in summary file.\n"
            f"File: {input_path}\n"
            f"Line: {line_number}\n"
            f"Column: {column_name}\n"
            f"Observed value: {value!r}"
        ) from error

    if parsed_value < 0:
        raise SystemExit(
            "ERROR: a negative integer value was found.\n"
            f"File: {input_path}\n"
            f"Line: {line_number}\n"
            f"Column: {column_name}\n"
            f"Observed value: {parsed_value}"
        )

    return parsed_value


def read_hapibd_segments(
    input_paths: Iterable[Path],
    threshold_cm: float,
    connection: sqlite3.Connection,
) -> tuple[int, int]:
    """
    Read raw Hap-IBD segments and aggregate them in SQLite.

    Returns
    -------
    segment_count
        Total number of segment rows processed.

    input_file_count
        Total number of input files processed.
    """

    batch: list[tuple] = []
    total_segment_count = 0
    input_file_count = 0

    for input_path in input_paths:
        input_file_count += 1

        print(
            f"Reading Hap-IBD file: {input_path}",
            file=sys.stderr,
        )

        with open_text_file(input_path) as input_handle:
            for line_number, line in enumerate(
                input_handle,
                start=1,
            ):
                stripped_line = line.rstrip("\r\n")

                if not stripped_line:
                    continue

                fields = stripped_line.split("\t")

                if len(fields) != EXPECTED_HAPIBD_COLUMNS:
                    raise SystemExit(
                        "ERROR: invalid Hap-IBD row.\n"
                        f"File: {input_path}\n"
                        f"Line: {line_number}\n"
                        f"Expected fields: {EXPECTED_HAPIBD_COLUMNS}\n"
                        f"Observed fields: {len(fields)}"
                    )

                sample1 = fields[0]
                sample2 = fields[2]

                if not sample1 or not sample2:
                    raise SystemExit(
                        "ERROR: an empty sample ID was found.\n"
                        f"File: {input_path}\n"
                        f"Line: {line_number}"
                    )

                if sample1 == sample2:
                    raise SystemExit(
                        "ERROR: an IBD segment connects a sample to itself.\n"
                        f"File: {input_path}\n"
                        f"Line: {line_number}\n"
                        f"Sample: {sample1}"
                    )

                try:
                    segment_length_cm = float(fields[7])
                except ValueError as error:
                    raise SystemExit(
                        "ERROR: invalid segment length.\n"
                        f"File: {input_path}\n"
                        f"Line: {line_number}\n"
                        f"Observed value: {fields[7]!r}"
                    ) from error

                if (
                    not math.isfinite(segment_length_cm)
                    or segment_length_cm < 0
                ):
                    raise SystemExit(
                        "ERROR: segment length must be a finite, "
                        "non-negative number.\n"
                        f"File: {input_path}\n"
                        f"Line: {line_number}\n"
                        f"Observed value: {segment_length_cm}"
                    )

                id1, id2 = canonicalize_pair(
                    sample1,
                    sample2,
                )

                passes_threshold = int(
                    segment_length_cm >= threshold_cm
                )

                threshold_length = (
                    segment_length_cm
                    if passes_threshold
                    else 0.0
                )

                batch.append(
                    (
                        id1,
                        id2,
                        segment_length_cm,
                        segment_length_cm**2,
                        segment_length_cm,
                        segment_length_cm,
                        passes_threshold,
                        threshold_length,
                    )
                )

                total_segment_count += 1

                if total_segment_count % 1_000_000 == 0:
                    print(
                        f"Processed {total_segment_count:,} Hap-IBD segments...",
                        file=sys.stderr,
                        flush=True,
                    )

                if len(batch) >= BATCH_SIZE:
                    insert_segment_batch(
                        connection,
                        batch,
                    )

    insert_segment_batch(
        connection,
        batch,
    )

    return total_segment_count, input_file_count


def read_chromosome_summaries(
    input_paths: Iterable[Path],
    threshold_cm: float,
    connection: sqlite3.Connection,
) -> tuple[int, int]:
    """
    Combine chromosome-level pair summaries in SQLite.

    Returns
    -------
    summary_row_count
        Total number of chromosome-level pair rows processed.

    input_file_count
        Total number of chromosome summary files processed.
    """

    threshold_count_column, threshold_length_column = (
        threshold_column_names(threshold_cm)
    )

    required_columns = {
        "ID1",
        "ID2",
        "number_of_IBD_segments",
        "total_IBD_length_cM",
        "sum_squared_IBD_length_cM",
        "min_IBD_length_cM",
        "max_IBD_length_cM",
        threshold_count_column,
        threshold_length_column,
    }

    batch: list[tuple] = []
    total_summary_rows = 0
    input_file_count = 0

    for input_path in input_paths:
        input_file_count += 1

        print(
            f"Reading chromosome summary: {input_path}",
            file=sys.stderr,
        )

        with open_text_file(input_path) as input_handle:
            reader = csv.DictReader(
                input_handle,
                delimiter="\t",
            )

            if reader.fieldnames is None:
                raise SystemExit(
                    "ERROR: chromosome summary has no header.\n"
                    f"File: {input_path}"
                )

            missing_columns = sorted(
                required_columns.difference(reader.fieldnames)
            )

            if missing_columns:
                formatted_columns = "\n  ".join(missing_columns)

                raise SystemExit(
                    "ERROR: chromosome summary is missing required columns.\n"
                    f"File: {input_path}\n"
                    f"Missing columns:\n  {formatted_columns}\n"
                    "Ensure that all chromosome summaries were generated "
                    "with this version of IBD_per_pair.py and the same "
                    "--threshold-cm value."
                )

            for line_number, row in enumerate(
                reader,
                start=2,
            ):
                sample1 = row["ID1"]
                sample2 = row["ID2"]

                if not sample1 or not sample2:
                    raise SystemExit(
                        "ERROR: an empty sample ID was found in a "
                        "chromosome summary.\n"
                        f"File: {input_path}\n"
                        f"Line: {line_number}"
                    )

                if sample1 == sample2:
                    raise SystemExit(
                        "ERROR: a chromosome summary contains a "
                        "self-pair.\n"
                        f"File: {input_path}\n"
                        f"Line: {line_number}\n"
                        f"Sample: {sample1}"
                    )

                id1, id2 = canonicalize_pair(
                    sample1,
                    sample2,
                )

                segment_count = parse_nonnegative_integer(
                    row["number_of_IBD_segments"],
                    "number_of_IBD_segments",
                    input_path,
                    line_number,
                )

                threshold_count = parse_nonnegative_integer(
                    row[threshold_count_column],
                    threshold_count_column,
                    input_path,
                    line_number,
                )

                total_length = parse_finite_float(
                    row["total_IBD_length_cM"],
                    "total_IBD_length_cM",
                    input_path,
                    line_number,
                    minimum=0.0,
                )

                total_squared_length = parse_finite_float(
                    row["sum_squared_IBD_length_cM"],
                    "sum_squared_IBD_length_cM",
                    input_path,
                    line_number,
                    minimum=0.0,
                )

                minimum_length = parse_finite_float(
                    row["min_IBD_length_cM"],
                    "min_IBD_length_cM",
                    input_path,
                    line_number,
                    minimum=0.0,
                )

                maximum_length = parse_finite_float(
                    row["max_IBD_length_cM"],
                    "max_IBD_length_cM",
                    input_path,
                    line_number,
                    minimum=0.0,
                )

                threshold_length = parse_finite_float(
                    row[threshold_length_column],
                    threshold_length_column,
                    input_path,
                    line_number,
                    minimum=0.0,
                )

                if segment_count < 1:
                    raise SystemExit(
                        "ERROR: a chromosome summary row has no segments.\n"
                        f"File: {input_path}\n"
                        f"Line: {line_number}"
                    )

                if threshold_count > segment_count:
                    raise SystemExit(
                        "ERROR: threshold segment count exceeds the total "
                        "segment count.\n"
                        f"File: {input_path}\n"
                        f"Line: {line_number}"
                    )

                if minimum_length > maximum_length:
                    raise SystemExit(
                        "ERROR: minimum segment length exceeds maximum "
                        "segment length.\n"
                        f"File: {input_path}\n"
                        f"Line: {line_number}"
                    )

                if threshold_length > total_length + 1e-8:
                    raise SystemExit(
                        "ERROR: threshold segment length exceeds the total "
                        "segment length.\n"
                        f"File: {input_path}\n"
                        f"Line: {line_number}"
                    )

                batch.append(
                    (
                        id1,
                        id2,
                        segment_count,
                        total_length,
                        total_squared_length,
                        minimum_length,
                        maximum_length,
                        threshold_count,
                        threshold_length,
                    )
                )

                total_summary_rows += 1

                if len(batch) >= BATCH_SIZE:
                    insert_summary_batch(
                        connection,
                        batch,
                    )

    insert_summary_batch(
        connection,
        batch,
    )

    return total_summary_rows, input_file_count


def write_pair_summary(
    connection: sqlite3.Connection,
    output_path: Path,
    threshold_cm: float,
) -> int:
    """
    Write pair-level summary statistics.

    Returns
    -------
    pair_count
        Number of sample pairs written.
    """

    threshold_count_column, threshold_length_column = (
        threshold_column_names(threshold_cm)
    )

    header = [
        "ID1",
        "ID2",
        "number_of_IBD_segments",
        "total_IBD_length_cM",
        "sum_squared_IBD_length_cM",
        "mean_IBD_length_cM",
        "min_IBD_length_cM",
        "max_IBD_length_cM",
        "sd_IBD_length_cM",
        threshold_count_column,
        threshold_length_column,
    ]

    select_statement = """
        SELECT
            id1,
            id2,
            segment_count,
            total_length,
            total_squared_length,
            minimum_length,
            maximum_length,
            threshold_count,
            threshold_length
        FROM pair_summary
        ORDER BY id1, id2
    """

    pair_count = 0

    with open_text_file(
        output_path,
        mode="wt",
    ) as output_handle:
        writer = csv.writer(
            output_handle,
            delimiter="\t",
            lineterminator="\n",
        )

        writer.writerow(header)

        for (
            id1,
            id2,
            segment_count,
            total_length,
            total_squared_length,
            minimum_length,
            maximum_length,
            threshold_count,
            threshold_length,
        ) in connection.execute(select_statement):
            mean_length = total_length / segment_count

            # Population variance across all segments detected for this pair.
            variance = (
                total_squared_length / segment_count
                - mean_length**2
            )

            # Floating-point rounding can occasionally produce a very small
            # negative value for a variance that should be zero.
            variance = max(
                0.0,
                variance,
            )

            standard_deviation = math.sqrt(
                variance
            )

            writer.writerow(
                [
                    id1,
                    id2,
                    segment_count,
                    format_number(total_length),
                    format_number(total_squared_length),
                    format_number(mean_length),
                    format_number(minimum_length),
                    format_number(maximum_length),
                    format_number(standard_deviation),
                    threshold_count,
                    format_number(threshold_length),
                ]
            )

            pair_count += 1

            if pair_count % 1_000_000 == 0:
                print(
                    f"Wrote {pair_count:,} pair summaries...",
                    file=sys.stderr,
                    flush=True,
                )

    return pair_count


def main() -> None:
    """Run raw-segment summarization or summary aggregation."""

    args = parse_arguments()
    validate_arguments(args)

    if args.temporary_directory is None:
        temporary_directory = args.output.parent
    else:
        temporary_directory = args.temporary_directory

    database_path = temporary_directory / (
        f"{args.output.name}.sqlite.tmp"
    )

    connection: sqlite3.Connection | None = None

    try:
        connection = initialize_database(
            database_path
        )

        if args.aggregate_summaries:
            summary_row_count, input_file_count = (
                read_chromosome_summaries(
                    input_paths=args.input,
                    threshold_cm=args.threshold_cm,
                    connection=connection,
                )
            )

            pair_count = write_pair_summary(
                connection=connection,
                output_path=args.output,
                threshold_cm=args.threshold_cm,
            )

            print(
                (
                    f"Processed {summary_row_count:,} chromosome-level "
                    f"pair rows from {input_file_count:,} summary file(s)."
                ),
                file=sys.stderr,
            )

            print(
                (
                    f"Wrote genome-wide summary statistics for "
                    f"{pair_count:,} sample pairs."
                ),
                file=sys.stderr,
            )

        else:
            segment_count, input_file_count = read_hapibd_segments(
                input_paths=args.input,
                threshold_cm=args.threshold_cm,
                connection=connection,
            )

            pair_count = write_pair_summary(
                connection=connection,
                output_path=args.output,
                threshold_cm=args.threshold_cm,
            )

            print(
                (
                    f"Processed {segment_count:,} IBD segments from "
                    f"{input_file_count:,} Hap-IBD file(s)."
                ),
                file=sys.stderr,
            )

            print(
                (
                    f"Wrote summary statistics for "
                    f"{pair_count:,} sample pairs."
                ),
                file=sys.stderr,
            )

        print(
            f"Output: {args.output}",
            file=sys.stderr,
        )

    finally:
        if connection is not None:
            connection.close()

        database_path.unlink(
            missing_ok=True
        )


if __name__ == "__main__":
    main()
