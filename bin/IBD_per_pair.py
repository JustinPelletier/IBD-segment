#!/usr/bin/env python3

"""
Generate pair-level IBD-sharing summary statistics.

The script has two operating modes.

1. Raw Hap-IBD segment mode
   ------------------------
   This is the default mode. One or more headerless Hap-IBD .ibd or
   .ibd.gz files are summarized.

   Each Hap-IBD row must contain eight tab-separated fields:

       ID1
       HAPLOTYPE1
       ID2
       HAPLOTYPE2
       CHROMOSOME
       START_BP
       END_BP
       LENGTH_CM

2. Chromosome-summary aggregation mode
   -----------------------------------
   When --aggregate-summaries is specified, the input files must be
   chromosome-level summaries previously generated by this script.

   The chromosome-level sufficient statistics are combined to generate
   an exact genome-wide summary without rereading every Hap-IBD segment.

The output contains one row for every pair sharing at least one detected
IBD segment. Pairs without detected segments are not written because
their absence from the edge list represents zero IBD sharing.

A disk-backed SQLite database is used to avoid loading all IBD segments
or all sample pairs into memory.
"""

import argparse
import csv
import gzip
import math
import sqlite3
import sys
from pathlib import Path
from typing import IO, Iterable


EXPECTED_HAPIBD_COLUMNS = 8
BATCH_SIZE = 100_000


def parse_arguments() -> argparse.Namespace:
    """Parse command-line arguments."""

    parser = argparse.ArgumentParser(
        description=(
            "Generate pair-level IBD-sharing summary statistics from "
            "raw Hap-IBD files or chromosome-level summary files."
        )
    )

    parser.add_argument(
        "--input",
        required=True,
        nargs="+",
        type=Path,
        help=(
            "One or more input files. By default, these must be "
            "headerless Hap-IBD .ibd or .ibd.gz files. When "
            "--aggregate-summaries is used, these must be chromosome-level "
            ".per_pair.tsv or .per_pair.tsv.gz files generated by this script."
        ),
    )

    parser.add_argument(
        "--output",
        required=True,
        type=Path,
        help="Output pair-summary file in .tsv or .tsv.gz format.",
    )

    parser.add_argument(
        "--threshold-cm",
        required=True,
        type=float,
        help=(
            "Segment-length threshold in centimorgans. The output reports "
            "the number and total length of segments greater than or equal "
            "to this threshold."
        ),
    )

    parser.add_argument(
        "--aggregate-summaries",
        action="store_true",
        help=(
            "Treat input files as chromosome-level pair summaries and "
            "combine them into a genome-wide pair summary."
        ),
    )

    parser.add_argument(
        "--temporary-directory",
        type=Path,
        default=None,
        help=(
            "Directory used for the temporary SQLite database. On a Slurm "
            "cluster, node-local storage such as SLURM_TMPDIR is strongly "
            "recommended."
        ),
    )
    return parser.parse_args()


def open_text_file(
    path: Path,
    mode: str = "rt",
) -> IO[str]:
    """Open a plain-text or gzip-compressed file."""

    if str(path).endswith(".gz"):
        return gzip.open(
            path,
            mode=mode,
            encoding="utf-8",
            newline="",
        )

    return path.open(
        mode=mode,
        encoding="utf-8",
        newline="",
    )


def validate_arguments(args: argparse.Namespace) -> None:
    """Validate input paths and numeric arguments."""

    if not math.isfinite(args.threshold_cm) or args.threshold_cm < 0:
        raise SystemExit(
            "ERROR: --threshold-cm must be a finite number greater than "
            "or equal to zero."
        )

    missing_files = [
        str(input_path)
        for input_path in args.input
        if not input_path.is_file()
    ]

    if missing_files:
        formatted_files = "\n  ".join(missing_files)

        raise SystemExit(
            "ERROR: the following input files do not exist:\n"
            f"  {formatted_files}"
        )

    if args.output.exists() and args.output.is_dir():
        raise SystemExit(
            f"ERROR: the output path is a directory: {args.output}"
        )
    
    if args.temporary_directory is not None:
        args.temporary_directory.mkdir(
            parents=True,
            exist_ok=True,
        )

    args.output.parent.mkdir(
        parents=True,
        exist_ok=True,
    )


def initialize_database(
    database_path: Path,
) -> sqlite3.Connection:
    """Create and initialize the temporary SQLite aggregation database."""

    database_path.unlink(missing_ok=True)

    connection = sqlite3.connect(database_path)

    connection.executescript(
        """
        PRAGMA page_size = 32768;
        PRAGMA journal_mode = OFF;
        PRAGMA synchronous = OFF;
        PRAGMA locking_mode = EXCLUSIVE;
        PRAGMA temp_store = MEMORY;
        PRAGMA cache_size = -2097152;
        PRAGMA mmap_size = 4294967296;

        CREATE TABLE pair_summary (
            id1                  TEXT    NOT NULL,
            id2                  TEXT    NOT NULL,
            segment_count        INTEGER NOT NULL,
            total_length         REAL    NOT NULL,
            total_squared_length REAL    NOT NULL,
            minimum_length       REAL    NOT NULL,
            maximum_length       REAL    NOT NULL,
            threshold_count      INTEGER NOT NULL,
            threshold_length     REAL    NOT NULL,

            PRIMARY KEY (id1, id2)
        ) WITHOUT ROWID;
        """
    )

    return connection


def canonicalize_pair(
    id1: str,
    id2: str,
) -> tuple[str, str]:
    """
    Return sample IDs in a consistent order.

    This ensures that ID1-ID2 and ID2-ID1 are treated as the same pair.
    """

    if id1 <= id2:
        return id1, id2

    return id2, id1


def format_number(value: float) -> str:
    """
    Format floating-point values without unnecessary trailing zeros.

    Ten significant digits preserve substantially more precision than
    Hap-IBD normally reports while keeping the output readable.
    """

    return format(value, ".10g")


def threshold_column_names(
    threshold_cm: float,
) -> tuple[str, str]:
    """Return threshold-dependent output column names."""

    threshold_label = format_number(threshold_cm)

    count_column = (
        f"number_of_segments_ge_{threshold_label}_cM"
    )

    length_column = (
        f"total_length_of_segments_ge_{threshold_label}_cM"
    )

    return count_column, length_column


def insert_segment_batch(
    connection: sqlite3.Connection,
    batch: list[tuple],
) -> None:
    """Insert or update a batch of individual Hap-IBD segments."""

    if not batch:
        return

    upsert_statement = """
        INSERT INTO pair_summary (
            id1,
            id2,
            segment_count,
            total_length,
            total_squared_length,
            minimum_length,
            maximum_length,
            threshold_count,
            threshold_length
        )
        VALUES (
            ?,
            ?,
            1,
            ?,
            ?,
            ?,
            ?,
            ?,
            ?
        )

        ON CONFLICT (id1, id2)
        DO UPDATE SET
            segment_count =
                pair_summary.segment_count + 1,

            total_length =
                pair_summary.total_length +
                excluded.total_length,

            total_squared_length =
                pair_summary.total_squared_length +
                excluded.total_squared_length,

            minimum_length =
                MIN(
                    pair_summary.minimum_length,
                    excluded.minimum_length
                ),

            maximum_length =
                MAX(
                    pair_summary.maximum_length,
                    excluded.maximum_length
                ),

            threshold_count =
                pair_summary.threshold_count +
                excluded.threshold_count,

            threshold_length =
                pair_summary.threshold_length +
                excluded.threshold_length
    """

    connection.executemany(
        upsert_statement,
        batch,
    )

    connection.commit()
    batch.clear()


